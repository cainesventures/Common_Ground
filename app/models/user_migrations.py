"""Schema migrations for users.db.

content.db is Alembic-managed. users.db is not: it is created by
``UserBase.metadata.create_all``, which creates missing tables and never
alters an existing one. So a changed ``UniqueConstraint`` in app/models takes
effect on a fresh database and is silently ignored on the production volume,
where the rows actually live. Anything structural therefore needs an explicit,
idempotent step here, called from ``init_db``.

SQLite cannot drop or rename a table-level constraint, so each migration is a
create-copy-swap rebuild run inside a single transaction.
"""

import logging

from sqlalchemy import text

logger = logging.getLogger(__name__)


# Both vote tables are re-keyed the same way, so the differences are data.
_VOTE_REBUILDS = (
    {
        "table": "councilmember_votes",
        "old_constraint": "uq_cm_vote_per_voter",
        "target": "councilmember_id",
        "ddl": """
            CREATE TABLE councilmember_votes__new (
                id VARCHAR NOT NULL,
                councilmember_id VARCHAR NOT NULL,
                user_id VARCHAR,
                vote VARCHAR NOT NULL,
                voter_token VARCHAR,
                created_at DATETIME,
                updated_at DATETIME,
                PRIMARY KEY (id),
                CONSTRAINT uq_cm_vote_per_user UNIQUE (councilmember_id, user_id),
                FOREIGN KEY(user_id) REFERENCES users (id)
            )
        """,
        "indexes": (
            "CREATE INDEX ix_councilmember_votes_councilmember_id"
            " ON councilmember_votes (councilmember_id)",
            "CREATE INDEX ix_councilmember_votes_user_id"
            " ON councilmember_votes (user_id)",
        ),
    },
    {
        "table": "legislation_votes",
        "old_constraint": "uq_vote_per_voter",
        "target": "legislation_id",
        "ddl": """
            CREATE TABLE legislation_votes__new (
                id VARCHAR NOT NULL,
                legislation_id VARCHAR NOT NULL,
                user_id VARCHAR,
                vote VARCHAR NOT NULL,
                voter_token VARCHAR,
                created_at DATETIME,
                updated_at DATETIME,
                PRIMARY KEY (id),
                CONSTRAINT uq_vote_per_user UNIQUE (legislation_id, user_id),
                FOREIGN KEY(user_id) REFERENCES users (id)
            )
        """,
        "indexes": (
            "CREATE INDEX ix_legislation_votes_legislation_id"
            " ON legislation_votes (legislation_id)",
            "CREATE INDEX ix_legislation_votes_user_id"
            " ON legislation_votes (user_id)",
        ),
    },
)


def migrate_vote_dedup_to_user_id(users_engine):
    """Re-key both vote tables from (target, voter_token) to (target, user_id).

    ``voter_token`` is generated by the client, so uniqueness on it was never
    an identity: a caller sending a fresh UUID per request got a fresh ballot
    every time. For council members the write path was also anonymous and
    unrate-limited, which meant the "Citizen Approval" percentage displayed on
    a named official's page could be set to any value by anyone.

    Three things happen per table, in one transaction:

      1. Rows with no ``user_id`` are dropped. A vote cannot be cast without
         an account after this change, so those rows can never be attributed
         to anyone, and leaving them in would keep a permanent un-auditable
         offset inside a number shown to readers as a count of people.
      2. Where one account holds several rows for the same target -- possible
         under the old key, one row per browser -- the most recently updated
         row is kept.
      3. ``voter_token`` becomes nullable. It is still written, as a record of
         which browser cast a vote, but it no longer dedupes and is no longer
         required.

    Idempotent: gated on the old constraint still being present in the stored
    schema, so a second run is a no-op.
    """
    for spec in _VOTE_REBUILDS:
        table, target = spec["table"], spec["target"]

        with users_engine.connect() as conn:
            row = conn.execute(
                text("SELECT sql FROM sqlite_master WHERE type='table' AND name=:t"),
                {"t": table},
            ).first()
        if not row or not row[0]:
            continue                              # table not created yet
        if spec["old_constraint"] not in row[0]:
            continue                              # already migrated

        logger.info("Migrating %s to dedupe on user_id...", table)
        with users_engine.begin() as conn:
            anon = conn.execute(
                text(f"SELECT COUNT(*) FROM {table} WHERE user_id IS NULL")
            ).scalar() or 0
            collapsed = conn.execute(text(
                f"SELECT COUNT(*) FROM (SELECT 1 FROM {table} "
                f"WHERE user_id IS NOT NULL GROUP BY {target}, user_id "
                f"HAVING COUNT(*) > 1)"
            )).scalar() or 0

            conn.execute(text(spec["ddl"]))
            # rowid breaks the tie so the surviving row is deterministic when
            # two share an updated_at, or both have NULL for it.
            conn.execute(text(f"""
                INSERT INTO {table}__new
                    (id, {target}, user_id, vote, voter_token, created_at, updated_at)
                SELECT id, {target}, user_id, vote, voter_token, created_at, updated_at
                FROM {table} AS v
                WHERE v.user_id IS NOT NULL
                  AND v.rowid = (
                    SELECT w.rowid FROM {table} AS w
                    WHERE w.{target} = v.{target} AND w.user_id = v.user_id
                    ORDER BY COALESCE(w.updated_at, w.created_at) DESC, w.rowid DESC
                    LIMIT 1
                  )
            """))
            conn.execute(text(f"DROP TABLE {table}"))
            conn.execute(text(f"ALTER TABLE {table}__new RENAME TO {table}"))
            for stmt in spec["indexes"]:
                conn.execute(text(stmt))
            kept = conn.execute(text(f"SELECT COUNT(*) FROM {table}")).scalar() or 0

        logger.info(
            "  %s migrated: %d rows kept, %d anonymous dropped, "
            "%d account(s) had duplicate rows collapsed",
            table, kept, anon, collapsed,
        )
