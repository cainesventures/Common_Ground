def test_bill_vote_fresh_tokens_do_not_stuff_the_ballot(as_user, test_db):
    leg = make_legislation(test_db, "v2")
    for _ in range(5):
        r = as_user.post(f"/api/legislation/{leg.id}/vote",
                         json={"vote": "support", "voter_token": _token()})
        assert r.status_code == 200

    # Bill tallies are nested: {member, anonymous, total}.
    assert r.json()["counts"]["total"]["support"] == 1
    assert test_db.query(LegislationVote).count() == 1


def test_bill_vote_change_updates_in_place(as_user, test_db):
    leg = make_legislation(test_db, "v3")
    as_user.post(f"/api/legislation/{leg.id}/vote", json={"vote": "support"})
    r = as_user.post(f"/api/legislation/{leg.id}/vote", json={"vote": "oppose"})
    total = r.json()["counts"]["total"]
    assert total["oppose"] == 1 and total["support"] == 0
    assert total["total"] == 1
    assert test_db.query(LegislationVote).count() == 1


def test_bill_vote_anonymous_tally_is_now_always_empty(as_user, test_db):
    """A vote cannot be cast without an account, so every vote is a member
    vote. The `anonymous` bucket is kept in the response because the frontend
    reads that shape, but nothing can land in it any more."""
    leg = make_legislation(test_db, "v7")
    r = as_user.post(f"/api/legislation/{leg.id}/vote", json={"vote": "support"})
    counts = r.json()["counts"]
    assert counts["member"]["support"] == 1
    assert counts["anonymous"]["total"] == 0


def test_bill_your_vote_comes_from_the_session(as_user, test_db):
    leg = make_legislation(test_db, "v4")
    as_user.post(f"/api/legislation/{leg.id}/vote", json={"vote": "neutral"})
    r = as_user.get(f"/api/legislation/{leg.id}/votes?voter_token={_token()}")
    assert r.json()["your_vote"] == "neutral"


def test_votes_on_separate_bills_are_independent(as_user, test_db):
    """The constraint is per (bill, account) -- not one vote site-wide."""
    a = make_legislation(test_db, "v5")
    b = make_legislation(test_db, "v6")
    as_user.post(f"/api/legislation/{a.id}/vote", json={"vote": "support"})
    as_user.post(f"/api/legislation/{b.id}/vote", json={"vote": "oppose"})
    assert test_db.query(LegislationVote).count() == 2


