# Legacy persona perspectives are no longer reader-facing
# ---------------------------------------------------------------------------
# The rows stay in the database (16,217 of them, used by the eval harness), but
# nothing a reader or a crawler can reach serves the text. These two tests are
# the guard: both failures would be silent, re-publishing unverified writing
# into the server-rendered HTML of every bill page.

def test_public_bill_payload_carries_no_perspective_text(client, test_db):
    leg = make_legislation(test_db, "p1")
    r = client.get(f"/api/legislation/{leg.id}")
    assert r.status_code == 200
    data = r.json()["data"]
    assert "perspectives" not in data
    # The count is still there -- the admin pipeline view filters on it.
    assert data["perspective_count"] == 0


def test_perspectives_endpoint_requires_dev_tier(client, test_db):
    leg = make_legislation(test_db, "p2")
    r = client.get(f"/api/legislation/{leg.id}/perspectives")
    assert r.status_code == 401


def test_bill_payload_carries_insights(client, test_db):
    """`two_lane_insights` replaced the persona panel as the factual block on a
    bill page, so it has to reach the client. It was withheld on purpose before
    (internal grounding provenance), which is exactly the kind of change that
    reverts quietly."""
    leg = make_legislation(test_db, "p3")
    leg.two_lane_insights = "1. Does a thing. 2. Does another thing."
    test_db.flush()
    r = client.get(f"/api/legislation/{leg.id}")
    assert r.status_code == 200
    assert r.json()["data"]["two_lane_insights"] == "1. Does a thing. 2. Does another thing."


