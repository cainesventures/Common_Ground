"""Vote integrity: one ballot per account, on both vote surfaces.

Both endpoints used to deduplicate on ``voter_token``, a UUID generated by the
client. These tests pin the behaviour that replaced it, because the failure
mode is silent -- a regression here does not raise, it just quietly lets the
publicly displayed tallies be set to whatever a caller likes.

Council member votes get the closer look: that write path was also anonymous
and unrate-limited, and the number it feeds ("Citizen Approval") is shown on a
named official's page.
"""

import uuid

import pytest

from app.auth import get_current_user, get_optional_user
from app.models import Councilmember, CouncilmemberVote, LegislationVote, User
from tests.conftest import make_legislation


def _token() -> str:
    return str(uuid.uuid4())


@pytest.fixture
def user(test_db):
    u = User(
        id="user_test_1",
        google_id="g1",
        email="voter@example.com",
        display_name="Voter One",
        subscription_tier="free",
    )
    test_db.add(u)
    test_db.flush()
    return u


@pytest.fixture
def member(test_db):
    m = Councilmember(id="cm_test_1", name="Test Member", district="1")
    test_db.add(m)
    test_db.flush()
    return m


@pytest.fixture
def as_user(client, user):
    """Authenticate the TestClient as `user` without going through OAuth."""
    from main import app

    app.dependency_overrides[get_current_user] = lambda: user
    app.dependency_overrides[get_optional_user] = lambda: user
    yield client
    app.dependency_overrides.pop(get_current_user, None)
    app.dependency_overrides.pop(get_optional_user, None)


# ---------------------------------------------------------------------------
# Council member approval votes
# ---------------------------------------------------------------------------

def test_cm_vote_requires_auth(client, member):
    """The UI already refused to vote without a session; the server must too."""
    r = client.post(
        f"/api/councilmembers/{member.id}/vote",
        json={"vote": "support", "voter_token": _token()},
    )
    assert r.status_code == 401


def test_cm_vote_fresh_tokens_do_not_stuff_the_ballot(as_user, test_db, member):
    """The original bug, stated as a test.

    Ten requests from one account, each with a brand-new voter_token -- which
    is all it took to move a public approval rating by ten votes. The tally
    must stay at one.
    """
    for _ in range(10):
        r = as_user.post(
            f"/api/councilmembers/{member.id}/vote",
            json={"vote": "support", "voter_token": _token()},
        )
        assert r.status_code == 200

    assert r.json()["counts"] == {"support": 1, "oppose": 0}
    assert test_db.query(CouncilmemberVote).count() == 1


def test_cm_vote_change_updates_in_place(as_user, test_db, member):
    as_user.post(f"/api/councilmembers/{member.id}/vote",
                 json={"vote": "support", "voter_token": _token()})
    r = as_user.post(f"/api/councilmembers/{member.id}/vote",
                     json={"vote": "oppose", "voter_token": _token()})
    assert r.json()["counts"] == {"support": 0, "oppose": 1}
    assert test_db.query(CouncilmemberVote).count() == 1


def test_cm_vote_token_is_optional(as_user, member):
    """voter_token is audit metadata now, so a client may omit it."""
    r = as_user.post(f"/api/councilmembers/{member.id}/vote", json={"vote": "support"})
    assert r.status_code == 200
    assert r.json()["counts"]["support"] == 1


def test_cm_vote_rejects_unknown_member(as_user):
    r = as_user.post("/api/councilmembers/cm_nope/vote", json={"vote": "support"})
    assert r.status_code == 404


def test_cm_your_vote_comes_from_the_session_not_the_token(as_user, member):
    """A stranger's token must not reveal, or stand in for, their vote."""
    as_user.post(f"/api/councilmembers/{member.id}/vote",
                 json={"vote": "oppose", "voter_token": _token()})
    # Someone else's token in the query string is ignored entirely.
    r = as_user.get(f"/api/councilmembers/{member.id}/votes?voter_token={_token()}")
    assert r.status_code == 200
    assert r.json()["your_vote"] == "oppose"


def test_cm_votes_anonymous_reader_sees_counts_but_no_vote(client, member):
    r = client.get(f"/api/councilmembers/{member.id}/votes")
    assert r.status_code == 200
    assert r.json()["your_vote"] is None


def test_cm_vote_rejects_invalid_values(as_user, member):
    assert as_user.post(f"/api/councilmembers/{member.id}/vote",
                        json={"vote": "maybe"}).status_code == 422
    assert as_user.post(f"/api/councilmembers/{member.id}/vote",
                        json={"vote": "support", "voter_token": "not-a-uuid"}
                        ).status_code == 422


